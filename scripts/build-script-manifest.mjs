/**
 * Write browser/index.json: one entry per browser console script.
 *
 * Sources are browser/*.js (standalone scripts) and the console scripts in
 * src/automation/ (which need src/automation/core.js pasted first). Node
 * modules in src/automation/ and core.js itself are left out. Each entry is
 * derived from the file by scripts/lib/script-manifest.mjs; see that file for
 * the fields.
 *
 * Usage:
 *   node scripts/build-script-manifest.mjs           # write browser/index.json
 *   node scripts/build-script-manifest.mjs --check   # fail when it is out of date
 *
 * @author nich (@nichxbt)
 * @license Apache-2.0
 */

import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describeScript } from './lib/script-manifest.mjs';
import { isNodeProgram } from './lib/is-node-program.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'browser', 'index.json');

/** Directories holding console scripts, relative to the repository root. */
const SOURCES = ['browser', 'src/automation'];

/** Files in those directories that are not tools of their own. */
const NOT_TOOLS = new Set(['src/automation/core.js']);

/**
 * Collect every console script and describe it.
 *
 * @returns {object} The manifest.
 */
export function buildManifest() {
  const scripts = [];
  const seen = new Map();
  for (const dir of SOURCES) {
    const files = readdirSync(join(ROOT, dir)).filter((f) => f.endsWith('.js')).sort();
    for (const file of files) {
      const path = `${dir}/${file}`;
      if (NOT_TOOLS.has(path)) continue;
      const source = readFileSync(join(ROOT, path), 'utf8');
      if (isNodeProgram(source)) continue;
      const id = file.replace(/\.js$/, '');
      if (seen.has(id)) {
        throw new Error(`Two scripts share the id "${id}": ${seen.get(id)} and ${path}. Rename one.`);
      }
      seen.set(id, path);
      scripts.push(describeScript({ id, path, source }));
    }
  }
  scripts.sort((a, b) => a.id.localeCompare(b.id));
  return {
    $comment: 'Generated by scripts/build-script-manifest.mjs from the scripts themselves. Do not edit by hand.',
    schemaVersion: 1,
    core: 'src/automation/core.js',
    count: scripts.length,
    scripts,
  };
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isMain) {
  // Config defaults are copied from the scripts verbatim, dashes included;
  // escape those so the file itself keeps to the house style.
  const text = JSON.stringify(buildManifest(), null, 2).replace(/[\u2013\u2014]/g, (c) => `\\u${c.charCodeAt(0).toString(16)}`) + '\n';
  const count = JSON.parse(text).count;
  if (process.argv.includes('--check')) {
    const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (current !== text) {
      console.error('browser/index.json is out of date. Run: node scripts/build-script-manifest.mjs');
      process.exit(1);
    }
    console.log(`browser/index.json is up to date (${count} scripts).`);
  } else {
    writeFileSync(OUT, text);
    console.log(`Wrote browser/index.json (${count} scripts).`);
  }
}
